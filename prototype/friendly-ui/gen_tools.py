"""Generate the prototype's tools/ pages from one mapping (#15).

Tool pages live on their own and can be referred to by several sections; each
section page has its own short intro and links to its tools. Each tool page is
a placeholder that lists the sections using it. Usage, from the repo root:

    python prototype/friendly-ui/gen_tools.py .

Re-running overwrites everything under tools/.
"""
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
OUT = ROOT / "tools"

# slug: (name, bootstrap icon)
TOOLS = {
    "lsaai": ("LSAAI", "bi-person-badge"),
    "perun": ("PERUN", "bi-people"),
    "slidetap": ("Slidetap", "bi-images"),
    "data-transporter": ("Data transporter", "bi-truck"),
    "metadata-standard": ("Metadata standard", "bi-file-earmark-text"),
    "rems": ("REMS", "bi-shield-check"),
    "discovery": ("Discovery", "bi-search"),
    "landing-pages": ("Landing pages", "bi-window"),
    "metrics": ("Metrics", "bi-bar-chart-line"),
    "grafana": ("Grafana", "bi-speedometer2"),
}

# slug: (title, icon, intro, [tool slugs])
SECTIONS = {
    "data-exploration": (
        "Data exploration tools", "bi-binoculars",
        "You can look around BigPicture without an account. These tools show what "
        "is in the archive, how much of it there is, and how it is described.",
        ["metrics", "grafana", "discovery", "metadata-standard", "landing-pages"]),
    "data-access": (
        "Data access tools", "bi-key",
        "Getting data takes a login, permission for a dataset, and knowing what you "
        "are asking for. These tools handle each part.",
        ["lsaai", "perun", "rems", "metadata-standard", "landing-pages", "discovery"]),
    "data-contributing": (
        "Data contributing tools", "bi-upload",
        "Sharing data means logging in, describing your slides in the agreed "
        "standard, and moving them securely into the archive. These tools do that.",
        ["lsaai", "perun", "slidetap", "data-transporter", "metadata-standard"]),
    "model-contributing": (
        "Model contributing tools", "bi-cpu",
        "Tools for contributing models. Information will follow.",
        []),
}

FRONT = ("# PROTOTYPE (#15): generated by prototype/friendly-ui/gen_tools.py\n"
         "css: ../prototype/friendly-ui/friendly-ui.css\n")


def tiles(items):
    """items: [(href, name, icon)] -> an A-style tile grid."""
    out = ['```{=html}', '<div class="fu-tiles">']
    for href, name, icon in items:
        out.append(f'  <div class="fu-tile">\n    <div class="fu-icon"><i class="bi {icon}"></i></div>\n'
                   f'    <h3><a class="stretched-link" href="{href}">{name}</a></h3>\n  </div>')
    out += ['</div>', '```']
    return "\n".join(out)


def write(name, text):
    (OUT / name).write_text(text, encoding="utf-8")
    print("wrote tools/" + name)


OUT.mkdir(exist_ok=True)

# overview
write("index.qmd", f"---\ntitle: Explore tools\n{FRONT}---\n\n"
      "BigPicture is built from a set of tools. Pick what you want to do to see "
      "the tools involved.\n\n"
      + tiles([(f"{s}.html", t, i) for s, (t, i, _, _) in SECTIONS.items()]) + "\n")

# section pages
for slug, (title, icon, intro, tools) in SECTIONS.items():
    body = intro + "\n\n"
    if tools:
        body += "## Tools\n\n" + tiles([(f"{t}.html", TOOLS[t][0], TOOLS[t][1]) for t in tools]) + "\n"
    write(f"{slug}.qmd", f"---\ntitle: {title}\n{FRONT}---\n\n{body}")

# tool pages
for slug, (name, icon) in TOOLS.items():
    used = [(s, t) for s, (t, _, _, tools) in SECTIONS.items() if slug in tools]
    used_md = "\n".join(f"- [{t}]({s}.qmd)" for s, t in used)
    write(f"{slug}.qmd", f"---\ntitle: {name}\n{FRONT}---\n\n"
          "::: {.callout-note}\n## Placeholder\nThis page will describe "
          f"{name}. Its content is not part of this prototype yet.\n:::\n\n"
          f"## Used for\n\n{used_md}\n")

# sidebar snippet for _quarto.yml (printed, pasted by hand once)
print("\n# sidebar contents:")
print("        - tools/index.qmd")
print("        - section: By purpose\n          contents:")
for s in SECTIONS:
    print(f"            - tools/{s}.qmd")
print("        - section: All tools\n          contents:")
for s in TOOLS:
    print(f"            - tools/{s}.qmd")
